using System;
using System.Buffers.Binary;
using System.Linq;
using System.Numerics;
using System.Reflection;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Update;

namespace MongoDB.EntityFrameworkCore.Storage;

internal static class RowVersion
{
    /// <summary>
    /// The length of a <c>byte[]</c> row version: an unsigned 64-bit counter, big-endian, so the bytes sort in counter order.
    /// </summary>
    internal const int ByteArrayLength = sizeof(ulong);

    /// <summary>
    /// A description of the property types the provider generates row versions for, for use in messages.
    /// </summary>
    internal const string SupportedTypeDescription =
        "a non-nullable int, uint, long or ulong (a counter), or a byte[] (an 8-byte big-endian counter)";

    internal static object GetRowVersion(this IUpdateEntry entry, IProperty property)
        => property.ClrType == typeof(byte[])
            ? GetByteArrayRowVersion(entry, property)
            : GetRowVersionInternalMethodInfo.MakeGenericMethod(property.ClrType).Invoke(null, [entry, property])!;

    internal static bool IsRowVersion(this IReadOnlyProperty property)
        => property is {IsConcurrencyToken: true, ValueGenerated: ValueGenerated.OnAddOrUpdate}
           && (property.ClrType == typeof(byte[]) || (!property.IsNullable && SupportedNumericRowVersionTypes.Contains(property.ClrType)));

    /// <summary>
    /// True for a property that EF treats as a row version (a concurrency token with <see cref="ValueGenerated.OnAddOrUpdate"/>,
    /// which is what <c>IsRowVersion()</c> and <c>[Timestamp]</c> configure) but that the provider cannot generate a value for, so
    /// its value would never change and the concurrency check would never fail.
    /// </summary>
    internal static bool IsUnsupportedRowVersion(this IReadOnlyProperty property)
        => property is {IsConcurrencyToken: true, ValueGenerated: ValueGenerated.OnAddOrUpdate} && !property.IsRowVersion();

    internal static string DefaultElementName => "_version";

    private static readonly Type[] SupportedNumericRowVersionTypes = [typeof(int), typeof(uint), typeof(long), typeof(ulong)];

    private static T GetRowVersionInternal<T>(IUpdateEntry entry, IProperty property) where T : INumber<T>
        => entry.GetCurrentValue<T>(property) + T.One;

    // A byte[] row version is the same counter as a ulong, held as 8 big-endian bytes: null or empty (a new entity) counts as zero,
    // so the first write stores 1. Any other length was not written by the provider, so it is refused rather than guessed at.
    private static byte[] GetByteArrayRowVersion(IUpdateEntry entry, IProperty property)
    {
        var current = entry.GetCurrentValue<byte[]?>(property);

        ulong counter = 0;
        if (current is {Length: > 0})
        {
            if (current.Length != ByteArrayLength)
            {
                throw new InvalidOperationException(
                    $"The row version property '{property.Name}' on entity type '{entry.EntityType.DisplayName()}' has a value of " +
                    $"{current.Length} bytes. A byte[] row version is generated by the provider and must be empty (a new entity) " +
                    $"or exactly {ByteArrayLength} bytes; do not assign it.");
            }

            counter = BinaryPrimitives.ReadUInt64BigEndian(current);
        }

        var next = new byte[ByteArrayLength];
        BinaryPrimitives.WriteUInt64BigEndian(next, checked(counter + 1));
        return next;
    }

    private static readonly MethodInfo GetRowVersionInternalMethodInfo =
        typeof(RowVersion).GetMethod(nameof(GetRowVersionInternal), BindingFlags.Static | BindingFlags.NonPublic)!;
}
